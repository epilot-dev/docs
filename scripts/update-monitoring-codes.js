#!/usr/bin/env node
/**
 * Generates the Integration Toolkit monitoring code reference from the snapshot
 * emitted by erp-integration-api.
 *
 * The snapshot is produced and asserted by
 * `packages/erp-utils/src/monitoring/code-catalog.test.ts` in that repo, so a code
 * added to the taxonomy without a description fails CI there. This script turns
 * that artifact into the published table — the docs never hand-maintain the list,
 * which is what kept the old hub-only catalog drifting.
 *
 * Usage:  npm run update-monitoring-codes
 * Assumes erp-integration-api is checked out alongside this repo (../).
 */

const fs = require('node:fs');
const path = require('node:path');

const SNAPSHOT = path.resolve(
  __dirname,
  '../../erp-integration-api/packages/erp-utils/src/monitoring/__snapshots__/monitoring-codes.json',
);
const OUT = path.resolve(
  __dirname,
  '../docs/integrations/integration-toolkit/monitoring/codes.md',
);

/** Rendering order and the operator-facing framing for each level. */
const LEVELS = [
  {
    key: 'error',
    heading: 'Error',
    blurb:
      'Something failed and the event did not do what it was meant to do. These are what the default alert rules watch.',
  },
  {
    key: 'warning',
    heading: 'Warning',
    blurb:
      'Processing continued, but something needs a human eye — often a retry in flight or a value nobody has mapped yet.',
  },
  {
    key: 'success',
    heading: 'Success',
    blurb: 'The event did what it was meant to do. Useful for confirming a sync actually landed.',
  },
  {
    key: 'info',
    heading: 'Info',
    blurb:
      'Lifecycle markers rather than outcomes: a message was queued, a duplicate was ignored, a step was skipped by configuration. Counted in total events, but excluded from the success rate.',
  },
];

function escapeCell(text) {
  return text.replace(/\|/g, '\\|');
}

function render(snapshot) {
  const { codes, families } = snapshot;
  const byLevel = new Map(LEVELS.map((l) => [l.key, []]));
  for (const entry of codes) {
    if (!byLevel.has(entry.level)) {
      throw new Error(`Unhandled level "${entry.level}" on code ${entry.code}`);
    }
    byLevel.get(entry.level).push(entry);
  }

  const sections = LEVELS.map(({ key, heading, blurb }) => {
    const rows = byLevel.get(key);
    return [
      `## ${heading}`,
      '',
      blurb,
      '',
      '| Code | What it means |',
      '|---|---|',
      ...rows.map((r) => `| \`${r.code}\` | ${escapeCell(r.description)} |`),
      '',
    ].join('\n');
  });

  const familySection = [
    '## Status-code families',
    '',
    'Some codes are generated from an upstream response rather than drawn from the fixed list above.',
    '',
    '| Pattern | Level | What it means |',
    '|---|---|---|',
    ...families.map(
      (f) => `| \`${f.pattern}\` | ${f.level} | ${escapeCell(f.description)} |`,
    ),
    '',
  ].join('\n');

  return `---
sidebar_position: 2
title: Monitoring Codes
description: Every monitoring code the Integration Toolkit emits, what it means, and what to do about it
slug: /integrations/integration-toolkit/monitoring/codes
---

{/* AUTOGENERATED — do not edit by hand.
    Source: erp-integration-api packages/erp-utils/src/monitoring/__snapshots__/monitoring-codes.json
    Regenerate: npm run update-monitoring-codes */}

# Monitoring Codes

Every monitoring event carries a **code** and a **level**. The code says what
happened; the level says how much you should care. Both are filterable in the
Integration Hub's [Monitoring tab](./overview.md) and through the events API.

There are ${codes.length} codes. You are most likely here because you saw one in a failed
event — find it below.

:::tip
A code's level is fixed. That is what makes alert rules scoped to \`_error_\` or
\`_warning_\` predictable — see [Alerting](./alerting.md#choosing-what-to-watch).
:::

${sections.join('\n')}${familySection}`;
}

const snapshot = JSON.parse(fs.readFileSync(SNAPSHOT, 'utf8'));
fs.writeFileSync(OUT, render(snapshot));
console.log(
  `Wrote ${path.relative(process.cwd(), OUT)} — ${snapshot.codes.length} codes, ${snapshot.families.length} famil${snapshot.families.length === 1 ? 'y' : 'ies'}`,
);
